namespace PrintGrid.UnitTests.Customer;

public sealed class PrusaPaintQuoteTests
{
    [Fact]
    public void Single_color_plate_uses_its_original_tool_settings_without_a_wipe_tower()
    {
        var settings = System.Text.Json.Nodes.JsonNode.Parse("""
            {"global":{},"extruder.0":{"material_print_temperature":200},
             "extruder.1":{"material_print_temperature":235,"material_diameter":2.85}}
            """)!.AsObject();
        var request = new QuoteSliceRequest("models/sample.3mf", "3MF", 1,
            "PLA", ["WHITE", "BLUE"], 1.24m, .2m, 30, 1, Guid.NewGuid());

        var profile = PrusaQuoteSlicer.BuildProfile(settings, request, 220, 220, 250,
            [2], new CuraQuoteOptions());

        var values = profile.Split('\n').Where(line => line.Contains(" = "))
            .Select(line => line.Split(" = ", 2)).ToDictionary(pair => pair[0], pair => pair[1]);
        values["temperature"].Should().Be("235");
        values["filament_diameter"].Should().Be("2.85");
        values["wipe_tower"].Should().Be("0");

        var result = PrusaQuoteSlicer.ParseResult([
            "; generated by PrusaSlicer 2.5.0 on 2026-11-24",
            "; filament used [g] = 12.34",
            "; total toolchanges = 0",
            "; estimated printing time (normal mode) = 1h 2m 3s"
        ], 1);
        result.Grams.Should().Equal(12.34m);
        result.Minutes.Should().Be(62.05m);
        result.ToolChanges.Should().Be(0);
    }

    [Fact]
    public void Quote_summary_reads_each_filament_and_normal_mode_time()
    {
        var result = PrusaQuoteSlicer.ParseResult(
        [
            "; generated by PrusaSlicer 2.5.0 on 2026-11-24 at 07:17:34 UTC",
            "; filament used [g] = 78.91, 78.94",
            "; total filament used [g] = 157.85",
            "; total toolchanges = 282",
            "; estimated printing time (normal mode) = 17h 9m 6s",
            "; estimated printing time (silent mode) = 17h 45m 6s"
        ], 2);

        result.Grams.Should().Equal(78.91m, 78.94m);
        result.Minutes.Should().Be(1029.1m);
        result.ToolChanges.Should().Be(282);
    }

    [Fact]
    public void Export_retains_indexed_geometry_and_remaps_painted_slots_on_separate_plates()
    {
        const string white = "filament:00000001";
        const string red = "filament:00000002";
        var model = new ThreeMfPackage.NativeDocument();
        model.GroupIds.UnionWith([white, red]);
        model.Palette[white] = "#FFFFFF";
        var vertices = new[] { Vector3.Zero, Vector3.UnitX * 10, Vector3.UnitY * 10, Vector3.UnitZ * 10 };
        model.Meshes.Add(new("1", "1", vertices, [new(0, 1, 2, "481", white), new(0, 3, 1, null, white)], 1));
        model.Meshes.Add(new("2", "2", vertices.Select(v => v + new Vector3(500, 500, 0)).ToArray(),
            [new(0, 1, 2, null, red), new(0, 3, 1, null, red)], 2));
        var temp = Directory.CreateTempSubdirectory("printgrid-paint-test-");
        try
        {
            var project = PrusaPaintProject.Write(model, ["BLUE", "WHITE"],
                [new ColorGroupAssignment(white, "WHITE"), new ColorGroupAssignment(red, "BLUE")],
                temp.FullName, 1, 220, 220, 250);
            project.Plates.Select(p => p.WidthMm).Should().Equal(10m, 10m);
            project.Plates.Select(p => p.RequiredBedWidthMm).Should().Equal(40m, 10m);
            project.Plates[1].Tools.Should().Equal(1);
            using var archive = ZipFile.OpenRead(project.Plates[0].Path);
            using var source = archive.GetEntry("3D/3dmodel.model")!.Open();
            var xml = XDocument.Load(source);
            var triangles = xml.Descendants().Where(x => x.Name.LocalName == "triangle").ToList();
            triangles.Should().HaveCount(2);
            var first = triangles[0];
            first.Attributes().Single(a => a.Name.LocalName == "mmu_segmentation").Value.Should().Be("841");
            archive.GetEntry("Metadata/Slic3r_PE.config").Should().BeNull();
            using var singleColorPlate = ZipFile.OpenRead(project.Plates[1].Path);
            using var singleColorMesh = singleColorPlate.GetEntry("3D/3dmodel.model")!.Open();
            XDocument.Load(singleColorMesh).Descendants().Attributes()
                .Should().NotContain(a => a.Name.LocalName == "mmu_segmentation");
        }
        finally { temp.Delete(recursive: true); }
    }
}
